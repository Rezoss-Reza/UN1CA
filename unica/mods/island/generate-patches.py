def write(name,s):
 s=''.join('\n' if not line.strip() else line for line in s.splitlines(True)).rstrip()+'\n'
 p=HERE/'patches'/name
 if p.exists() and p.read_text()!=s: shutil.copy2(p,str(p)+'.bak.'+datetime.datetime.now().strftime('%Y%m%d_%H%M%S_%f'))
 p.parent.mkdir(parents=True,exist_ok=True)
 p.write_text(s);print(p)
def addition(name,text):
 lines=text.splitlines(keepends=True)
 return f'diff --git a/{name} b/{name}\nnew file mode 100644\n--- /dev/null\n+++ b/{name}\n@@ -0,0 +1,{len(lines)} @@\n'+''.join('+'+x for x in lines)+'\n'
def diff(name,old,new):
 return f'diff --git a/{name} b/{name}\n'+''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='a/'+name,tofile='b/'+name,n=3))
def methods(text, transform):
 return re.sub(r'^\.method\b.*?^\.end method\n',lambda m:transform(m.group()),text,flags=re.M|re.S)
def entry(m,code,needs_register=False):
 if needs_register:
  n=int(re.search(r'    \.locals (\d+)',m).group(1))
  if n==0:
   if re.search(r'\bv0\b',m):raise ValueError('Parameter v0 alias requires manual review')
   m=m.replace('    .locals 0','    .locals 1',1)
 # Insert after register/parameter annotations and before first instruction/label.
 lines=m.splitlines(True);i=1;depth=0
 while i<len(lines):
  s=lines[i].strip()
  if s.startswith('.annotation') or s.startswith('.subannotation'):depth+=1
  if s.startswith('.end annotation') or s.startswith('.end subannotation'):depth-=1;i+=1;continue
  if depth or not s or s.startswith('.') or s.startswith('#'):i+=1;continue
  break
 return ''.join(lines[:i])+code+'\n'+''.join(lines[i:])
def guard(m,call,result='void'):
 end='    return-void\n' if result=='void' else '    const/4 v0, 0x0\n    return v0\n'
 return entry(m,call+'    move-result v0\n    if-eqz v0, :cond_cipher_original\n'+end+'\n    :cond_cipher_original\n',True)
def wrapper(text,name,proto,args,ret,owner="IslandView"):
 pattern=r'^\.method ([^\n]*?)\b'+re.escape(name+proto)+r'\n.*?^\.end method\n'
 hit=re.search(pattern,text,flags=re.M|re.S)
 if not hit:raise ValueError('Missing renderer method '+name+proto)
 original=hit.group();renamed=original.replace(name+proto,'cipherOriginal_'+name+proto,1)
 access=hit.group(1)
 out=f'.method {access}{name}{proto}\n    .locals 1\n\n    :try_start_cipher\n    invoke-'+('direct' if 'private' in access else 'virtual')+' {'+args+'}, Ldev/android/dynamicisland/island/'+owner+';->cipherOriginal_'+name+proto+'\n'
 if ret=='Z':out+='    move-result v0\n'
 out+='    :try_end_cipher\n    .catch Ljava/lang/Throwable; {:try_start_cipher .. :try_end_cipher} :catch_cipher\n\n'
 out+= '    return v0\n' if ret=='Z' else '    return-void\n'
 out+='\n    :catch_cipher\n    move-exception v0\n    invoke-static {v0}, '+BR+'->fail(Ljava/lang/Throwable;)V\n'
 out+= '    const/4 v0, 0x0\n    return v0\n' if ret=='Z' else '    return-void\n'
 out+='.end method\n'
 return text[:hit.start()]+renamed+'\n'+out+text[hit.end():]

